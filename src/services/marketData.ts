// Helper to generate realistic historical candles
export function generateHistoricalCandles(basePrice: number, count: number = 80, intervalMinutes: number = 1): Candle[] {
  const candles: Candle[] = [];
  const now = Date.now();
  const intervalMs = intervalMinutes * 60 * 1000;
  let currentClose = basePrice;
  const volatility = basePrice * (intervalMinutes === 1 ? 0.0008 : intervalMinutes === 5 ? 0.0018 : 0.0035);

  for (let i = count; i >= 0; i--) {
    const time = now - i * intervalMs;
    const delta = (Math.random() - 0.49) * volatility;
    const open = currentClose;
    const close = Math.max(open * 0.5, open + delta);
    const wickHigh = Math.random() * (volatility * 0.8);
    const wickLow = Math.random() * (volatility * 0.8);
    const high = Math.max(open, close) + wickHigh;
    const low = Math.min(open, close) - wickLow;
    const volume = Math.floor(Math.random() * 50000) + 10000;

    candles.push({
      time,
      open: Number(open.toFixed(basePrice < 5 ? 4 : 2)),
      high: Number(high.toFixed(basePrice < 5 ? 4 : 2)),
      low: Number(low.toFixed(basePrice < 5 ? 4 : 2)),
      close: Number(close.toFixed(basePrice < 5 ? 4 : 2)),
      volume,
    });

    currentClose = close;
  }

  return candles;
}

// Fetch real prices from Binance API for crypto
export async function fetchLiveCryptoPrices(): Promise<Record<string, number>> {
  try {
    const res = await fetch('https://api.binance.com/api/v3/ticker/price');
    if (!res.ok) return {};
    const data: { symbol: string; price: string }[] = await res.json();
    const priceMap: Record<string, number> = {};
    for (const item of data) {
      priceMap[item.symbol] = parseFloat(item.price);
    }
    return priceMap;
  } catch {
    return {};
  }
}
